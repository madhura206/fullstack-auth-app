// models/User.js
import mongoose from "mongoose";

// Define schema
const userSchema = new mongoose.Schema({
  name: {
    type: String,
    required: true,
  },
  email: {
    type: String,
    required: true,
    unique: true,
  },
  password: {
    type: String,
    required: true,
  },
  dateCreated: {
    type: Date,
    default: Date.now,
  },
});

// Export model
const User = mongoose.model("User", userSchema);
export default User;
